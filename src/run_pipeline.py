"""Run the whole pipeline: load CSVs -> SQL layers -> monitoring -> campaign review -> charts -> summary.

Usage:
    python -m src.run_pipeline --data raw      # real Olist data in data/raw/
    python -m src.run_pipeline --data sample   # synthetic sample, for a quick test
"""
import argparse
from pathlib import Path

import duckdb
import pandas as pd

from . import campaign, charts, config, load, monitor


def run(data: str = "raw", report_dir: Path = config.REPORT_DIR, db_path: Path | None = None) -> dict:
    data_dir = config.DATA_DIRS[data]
    tables_dir, fig_dir = report_dir / "tables", report_dir / "figures"
    for d in (tables_dir, fig_dir, config.BUILD_DIR):
        d.mkdir(parents=True, exist_ok=True)
    db_path = db_path or config.BUILD_DIR / f"olist_{data}.duckdb"

    con = duckdb.connect(str(db_path))
    print(f"[1/6] Loading CSVs from {data_dir}")
    load.load_raw(con, data_dir)
    print("[2/6] Building DWD / ADS tables (sql/)")
    load.build_layers(con)
    counts = load.row_counts(con)

    daily = con.execute("SELECT * FROM ads_daily_metrics").df()
    cat_month = con.execute("SELECT * FROM ads_category_month").df()
    review_rep = con.execute("SELECT * FROM ads_review_repurchase").df()

    print("[3/6] Monitoring: anomaly detection and daily reports")
    anomalies = monitor.detect_anomalies(daily)
    for day in (config.CAMPAIGN["peak_day"], config.ANALYSIS_END):
        (report_dir / f"daily_report_{day}.md").write_text(monitor.daily_report(daily, anomalies, day), encoding="utf-8")

    print("[4/6] Campaign review")
    camp = campaign.review(con)

    print("[5/6] Exporting tables (for Tableau) and charts")
    daily.to_csv(tables_dir / "daily_metrics.csv", index=False)
    cat_month.to_csv(tables_dir / "category_month.csv", index=False)
    review_rep.to_csv(tables_dir / "review_repurchase.csv", index=False)
    anomalies.to_csv(tables_dir / "anomalies.csv", index=False)
    camp["kpi"].to_csv(tables_dir / "campaign_kpi.csv")
    camp["decomposition"].to_csv(tables_dir / "campaign_decomposition.csv", index=False)
    camp["categories"].to_csv(tables_dir / "campaign_categories.csv", index=False)

    gmv_change = camp["kpi"].at["gmv", "change"]
    charts.daily_gmv(daily, anomalies, fig_dir / "daily_gmv_alerts.png")
    charts.category_share(cat_month, fig_dir / "category_share.png")
    charts.review_repurchase(review_rep, fig_dir / "review_repurchase.png")
    charts.campaign_decomposition(camp["decomposition"], gmv_change, fig_dir / "campaign_decomposition.png")

    print("[6/6] Writing reports/summary.md")
    summary = build_summary(data, counts, daily, anomalies, cat_month, review_rep, camp)
    (report_dir / "summary.md").write_text(summary, encoding="utf-8")
    con.close()
    print(f"Done. See {report_dir / 'summary.md'}")
    return {"counts": counts, "daily": daily, "anomalies": anomalies, "campaign": camp}


def build_summary(data, counts, daily, anomalies, cat_month, review_rep, camp) -> str:
    kpi, dec = camp["kpi"], camp["decomposition"]
    valid = daily[daily["orders"] > 0]
    top_cat = cat_month.groupby("category")["gmv"].sum().sort_values(ascending=False)
    top3 = ", ".join(f"{c} ({v / top_cat.sum():.1%})" for c, v in top_cat.head(3).items())
    rr = review_rep.set_index("first_order_review")["repurchase_rate"]
    lead = dec.sort_values("share_of_gmv_change", ascending=False).iloc[0]
    cats = camp["categories"].head(3)

    note = ("> **Synthetic sample data** — numbers below only prove the pipeline runs. "
            "Run with `--data raw` for real results.\n\n" if data == "sample" else "")
    lines = [
        "# Results summary (generated by the pipeline)", "", note,
        f"Data: `{data}` · Analysis window {config.ANALYSIS_START} to {config.ANALYSIS_END}", "",
        "## Data volume",
        f"- Orders: {counts['orders']:,} · Order items: {counts['order_items']:,} · Reviews: {counts['order_reviews']:,}",
        "",
        "## Trade overview",
        f"- Total GMV in window: {daily['gmv'].sum():,.0f} BRL from {daily['orders'].sum():,} valid orders",
        f"- Average AOV: {daily['gmv'].sum() / daily['orders'].sum():,.1f} BRL",
        f"- Days with orders: {len(valid)} of {len(daily)}",
        f"- Top 3 categories by GMV share: {top3}",
        "",
        "## Monitoring",
        f"- {len(anomalies)} alerts across {anomalies['dt'].nunique()} days "
        f"(rule: |z| > {config.Z_THRESHOLD:g} vs previous {config.ROLLING_DAYS} days)",
    ]
    for _, r in anomalies.sort_values("z_score", key=abs, ascending=False).head(5).iterrows():
        lines.append(f"  - {pd.Timestamp(r["dt"]).date()} · {r.metric} {r.direction} · z = {r.z_score:.1f}")
    lines += [
        "",
        f"## Campaign review: {config.CAMPAIGN['name']}",
        f"- Promo week GMV vs average baseline week: {kpi.at['gmv', 'change']:+.1%}",
        f"- Buyers {kpi.at['buyers', 'change']:+.1%} · Orders per buyer {kpi.at['orders_per_buyer', 'change']:+.1%} · "
        f"AOV {kpi.at['aov', 'change']:+.1%}",
        f"- Largest driver: {lead.driver} ({lead.share_of_gmv_change:.0%} of the GMV change in log terms)",
        "- Categories adding the most GMV: " + ", ".join(
            f"{r.category} (+{r.incremental_gmv:,.0f})" for r in cats.itertuples()),
        "",
        "## Reviews and repurchase",
    ]
    for score in ["1", "2", "3", "4", "5"]:
        if score in rr.index:
            lines.append(f"- First order rated {score}: repurchase rate {rr[score]:.1%}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--data", choices=["raw", "sample"], default="raw")
    run(p.parse_args().data)
